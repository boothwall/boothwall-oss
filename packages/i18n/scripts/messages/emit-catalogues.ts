import type { ArgumentType, Catalogue } from "./read-catalogues.ts";

const TS: Record<ArgumentType, string> = {
  number: "number",
  string: "string",
  date: "Date | number",
  any: "string | number",
};

const header = (source: string) =>
  `// Generated by boothwall-messages from ${source}. Do not edit; run the package's messages script.\n`;

const key = (name: string) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

const typeName = (area: string) =>
  area.replace(/(?:^|-)([a-z0-9])/g, (_, c: string) => c.toUpperCase());

/**
 * The generated folder: one module per language and area, the typed values of every English
 * message (one file per area, so none grows with the whole catalogue), and lazy loaders. `runtime` is where `Messages`/`CatalogueLoaders` come from
 * (`@boothwall/i18n`, or `#catalogue` inside this package).
 */
export function emitCatalogues(catalogues: readonly Catalogue[], runtime: string) {
  const files = new Map<string, string>();
  const areas = new Map<string, string[]>();
  const typed: string[] = [];
  for (const { language, area, messages, args } of catalogues) {
    files.set(
      `${language}/${area}.ts`,
      `${header(`messages/${language}/${area}.json`)}import type { Messages } from "${runtime}";\n\n` +
        `export const messages: Messages = ${JSON.stringify(messages)};\n`,
    );
    areas.set(area, [...(areas.get(area) ?? []), language]);
    if (language !== "en") continue;
    const values = Object.entries(args).map(([id, names]) => {
      const fields = Object.entries(names).map(([name, type]) => `${key(name)}: ${TS[type]}`);
      return `  ${JSON.stringify(id)}: ${fields.length ? `{ ${fields.join("; ")} }` : "Record<never, never>"};`;
    });
    files.set(
      `values/${area}.ts`,
      `${header(`messages/en/${area}.json`)}export type Values = {\n${values.sort().join("\n")}\n};\n`,
    );
    typed.push(area);
  }
  typed.sort();
  files.set(
    "message-values.ts",
    header("messages/en") +
      typed
        .map((a) => `import type { Values as ${typeName(a)} } from "./values/${a}.ts";\n`)
        .join("") +
      `\n/** Every English message's values, by id. */\nexport type MessageValues = ${
        typed.map(typeName).join(" & ") || "Record<never, never>"
      };\n`,
  );
  const loaders = [...areas]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([area, languages]) =>
        `  ${JSON.stringify(area)}: {\n${languages
          .map((l) => `    ${l}: () => import("./${l}/${area}.ts"),`)
          .join("\n")}\n  },`,
    );
  files.set(
    "index.ts",
    `${header("messages/")}import type { CatalogueLoaders } from "${runtime}";\n\n` +
      `export type { MessageValues } from "./message-values.ts";\n\n` +
      `export const catalogues = {\n${loaders.join("\n")}\n} satisfies CatalogueLoaders;\n`,
  );
  return files;
}
